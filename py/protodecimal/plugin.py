"""protoc plugin implementation: decimal.Decimal accessors for
protodecimal.v1.Decimal fields.

For every generated <name>_pb2.py that contains fields of type
protodecimal.v1.Decimal, this plugin emits a sibling
<name>_pb2_decimal.py module. Importing that module attaches
``get_<field>_decimal()`` / ``set_<field>_decimal(value)`` methods to each
generated message class (mirroring the Go plugin's Get<Field>Decimal /
Set<Field>Decimal):

    import example.orderbook_pb2_decimal  # attaches the methods
    level = orderbook_pb2.Level()
    level.set_price_decimal(Decimal("123.4500"))
    level.get_price_decimal()  # -> Decimal('123.4500')

Methods (not properties) because the upb-backed message classes intercept
instance attribute writes, so property setters can never fire.

Repeated Decimal fields get list[Decimal] variants. Oneof members work
transparently (setting selects the case). Map fields with Decimal values
are not supported and are skipped.

Invocation: after `pip install .` the plugin is on PATH as
protoc-gen-python-decimal (console-script entry point); inside this repo
the wrapper script py/protoc-gen-python-decimal runs it without
installation. Either way:

    protoc -I proto \
        --plugin=protoc-gen-python-decimal=$(pwd)/py/protoc-gen-python-decimal \
        --python-decimal_out=py \
        proto/example/v1/orderbook.proto

With the default options, the generated module also attaches a fast_encode
static method to each message holding a decimal; see protodecimal/fast.py.

Options (comma-separated in --python-decimal_opt):

    decimal_type=<full proto name>   default: protodecimal.v1.Decimal
    conv=<python module>             default: protodecimal.conv
"""

import sys

from google.protobuf import descriptor_pb2
from google.protobuf.compiler import plugin_pb2

from protodecimal import __version__

_FIELD = descriptor_pb2.FieldDescriptorProto

DEFAULT_DECIMAL_TYPE = "protodecimal.v1.Decimal"
DEFAULT_CONV_MODULE = "protodecimal.conv"

_HELPERS = '''\

def _attach_singular(cls, name):
    def _get(self):
        """Return the field as a decimal.Decimal (zero when unset)."""
        return _conv.to_decimal(getattr(self, name))

    def _set(self, value):
        """Set the field from a decimal.Decimal."""
        _conv.fill(getattr(self, name), value)

    setattr(cls, f"get_{name}_decimal", _get)
    setattr(cls, f"set_{name}_decimal", _set)


def _attach_repeated(cls, name):
    def _get(self):
        """Return the repeated field as a list of decimal.Decimal."""
        return [_conv.to_decimal(m) for m in getattr(self, name)]

    def _set(self, values):
        """Replace the repeated field from an iterable of decimal.Decimal.

        Values are encoded first, so a rejected one leaves the field intact.
        """
        encoded = getattr(type(self)(), name)
        for value in values:
            _conv.fill(encoded.add(), value)
        field = getattr(self, name)
        del field[:]
        field.extend(encoded)

    setattr(cls, f"get_{name}_decimal", _get)
    setattr(cls, f"set_{name}_decimal", _set)

'''


def parse_parameters(parameter):
    params = {}
    for item in filter(None, (parameter or "").split(",")):
        key, _, value = item.partition("=")
        params[key.strip()] = value.strip()
    return params


def module_name(proto_name):
    """Mirror protoc's python module naming: a/b/x.proto -> a.b.x_pb2."""
    base = proto_name[: -len(".proto")] if proto_name.endswith(".proto") else proto_name
    return base.replace("-", "_").replace("/", ".") + "_pb2"


def iter_messages(messages, prefix=""):
    for msg in messages:
        if msg.options.map_entry:
            continue
        path = prefix + msg.name
        yield path, msg
        yield from iter_messages(msg.nested_type, prefix=path + ".")


def collect(file_proto, decimal_type):
    """Yield (class_path, field_name, is_repeated) for every Decimal field."""
    wanted = "." + decimal_type
    for class_path, msg in iter_messages(file_proto.message_type):
        for field in msg.field:
            # Map fields reference their synthesized MapEntry type, so they
            # never match `wanted` and are skipped automatically.
            if field.type == _FIELD.TYPE_MESSAGE and field.type_name == wanted:
                yield class_path, field.name, field.label == _FIELD.LABEL_REPEATED


def render(file_proto, entries, conv_module, decimal_type):
    pb2_module = module_name(file_proto.name)
    # fast_encode writes the default wire layout directly, so it can't be used
    # with a custom conversion module or decimal type.
    fast = conv_module == DEFAULT_CONV_MODULE and decimal_type == DEFAULT_DECIMAL_TYPE
    lines = [
        "# Code generated by protoc-gen-python-decimal. DO NOT EDIT.",
        f"# source: {file_proto.name}",
        f'"""decimal.Decimal accessors for {pb2_module}.',
        "",
        "Importing this module attaches `get_<field>_decimal` and",
        "`set_<field>_decimal` methods to the generated message classes.",
        '"""',
        "",
        "import importlib",
        "",
        f'_conv = importlib.import_module("{conv_module}")',
        f'_pb2 = importlib.import_module("{pb2_module}")',
        '_fast = importlib.import_module("protodecimal.fast")' if fast else "",
        "",
        _HELPERS,
    ]
    for class_path, field_name, repeated in entries:
        attach = "_attach_repeated" if repeated else "_attach_singular"
        lines.append(f'{attach}(_pb2.{class_path}, "{field_name}")')
    if fast:
        lines.append("_fast.attach_file(_pb2)")
    lines.append("")
    return "\n".join(lines)


def main():
    if sys.argv[1:] == ["--version"]:
        print(f"protoc-gen-python-decimal {__version__}")
        return
    request = plugin_pb2.CodeGeneratorRequest.FromString(sys.stdin.buffer.read())
    params = parse_parameters(request.parameter)
    decimal_type = params.get("decimal_type", DEFAULT_DECIMAL_TYPE).lstrip(".")
    conv_module = params.get("conv", DEFAULT_CONV_MODULE)

    response = plugin_pb2.CodeGeneratorResponse()
    response.supported_features = (
        plugin_pb2.CodeGeneratorResponse.FEATURE_PROTO3_OPTIONAL
    )

    files_by_name = {f.name: f for f in request.proto_file}
    for name in request.file_to_generate:
        file_proto = files_by_name[name]
        entries = list(collect(file_proto, decimal_type))
        if not entries:
            continue
        out = response.file.add()
        out.name = name[: -len(".proto")].replace("-", "_") + "_pb2_decimal.py"
        out.content = render(file_proto, entries, conv_module, decimal_type)

    sys.stdout.buffer.write(response.SerializeToString())


if __name__ == "__main__":
    main()
