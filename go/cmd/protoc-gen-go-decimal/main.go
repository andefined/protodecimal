// protoc-gen-go-decimal generates github.com/shopspring/decimal accessors
// for proto message fields whose type is protodecimal.v1.Decimal.
//
// It runs alongside protoc-gen-go and writes a sibling
// <name>_decimal.pb.go file into the same Go package, containing for each
// matching field:
//
//	func (x *Msg) Get<Field>Decimal() decimal.Decimal
//	func (x *Msg) Set<Field>Decimal(d decimal.Decimal)
//
// and for repeated fields:
//
//	func (x *Msg) Get<Field>Decimal() []decimal.Decimal
//	func (x *Msg) Set<Field>Decimal(ds []decimal.Decimal)
//
// Oneof members are supported (the setter installs the oneof wrapper).
// Map fields with Decimal values are not supported and are skipped.
// The generated code targets protoc-gen-go's open struct API.
//
// With the default decimal_type and conv, each proto3 message that holds a
// decimal also gets a <Msg>Decimals struct whose Unmarshal method decodes wire
// bytes without protobuf objects. Messages using maps, oneofs, proto3 optional,
// cyclic types, or message types from other files don't get one.
//
// Options (comma-separated in --go-decimal_opt):
//
//	decimal_type=<full proto name>
//	    Proto message treated as the Decimal wire type.
//	    Default: protodecimal.v1.Decimal
//	conv=<go import path>
//	    Package providing ToShopspring/FromShopspring for that wire type.
//	    Default: github.com/andefined/protodecimal/go/decimalconv
//	module=, paths=
//	    Standard protoc-gen-go output-path options; handled by protogen.
package main

import (
	"flag"
	"fmt"
	"os"
	"runtime/debug"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"
)

const (
	shopspringImport = protogen.GoImportPath("github.com/shopspring/decimal")

	defaultDecimalType = protoreflect.FullName("protodecimal.v1.Decimal")
	defaultConvImport  = protogen.GoImportPath("github.com/andefined/protodecimal/go/decimalconv")
)

type config struct {
	decimalType protoreflect.FullName
	convImport  protogen.GoImportPath
}

func main() {
	if len(os.Args) == 2 && os.Args[1] == "--version" {
		fmt.Println("protoc-gen-go-decimal", version())
		return
	}
	var flags flag.FlagSet
	decimalType := flags.String("decimal_type", string(defaultDecimalType),
		"fully-qualified proto name of the Decimal message")
	convImport := flags.String("conv", string(defaultConvImport),
		"Go import path of the conversion package")

	protogen.Options{ParamFunc: flags.Set}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		cfg := config{
			decimalType: protoreflect.FullName(strings.TrimLeft(*decimalType, ".")),
			convImport:  protogen.GoImportPath(*convImport),
		}
		for _, file := range gen.Files {
			if file.Generate {
				generateFile(gen, file, cfg)
			}
		}
		return nil
	})
}

// version is the module version recorded by go install, or what the Go
// toolchain records for a build from a checkout.
func version() string {
	if info, ok := debug.ReadBuildInfo(); ok {
		return info.Main.Version
	}
	return "(unknown)"
}

func generateFile(gen *protogen.Plugin, file *protogen.File, cfg config) {
	var targets []*protogen.Message
	var walk func([]*protogen.Message)
	walk = func(messages []*protogen.Message) {
		for _, m := range messages {
			if m.Desc.IsMapEntry() {
				continue
			}
			if len(decimalFields(m, cfg)) > 0 {
				targets = append(targets, m)
			}
			walk(m.Messages) // recurse into nested message declarations
		}
	}
	walk(file.Messages)
	if len(targets) == 0 {
		return
	}

	g := gen.NewGeneratedFile(file.GeneratedFilenamePrefix+"_decimal.pb.go", file.GoImportPath)
	g.P("// Code generated by protoc-gen-go-decimal. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()
	for _, m := range targets {
		for _, f := range decimalFields(m, cfg) {
			generateField(g, m, f, cfg)
		}
	}
	generateDecoders(g, decodedMessages(file, cfg), cfg)
}

func decimalFields(m *protogen.Message, cfg config) []*protogen.Field {
	var out []*protogen.Field
	for _, f := range m.Fields {
		// Map fields reference the synthesized MapEntry message, so they
		// never match decimalType; the explicit check documents the intent.
		if f.Desc.IsMap() || f.Message == nil {
			continue
		}
		if f.Message.Desc.FullName() == cfg.decimalType {
			out = append(out, f)
		}
	}
	return out
}

func generateField(g *protogen.GeneratedFile, m *protogen.Message, f *protogen.Field, cfg config) {
	dec := g.QualifiedGoIdent(shopspringImport.Ident("Decimal"))
	to := g.QualifiedGoIdent(cfg.convImport.Ident("ToShopspring"))
	from := g.QualifiedGoIdent(cfg.convImport.Ident("FromShopspring"))

	if f.Desc.IsList() {
		pbElem := g.QualifiedGoIdent(f.Message.GoIdent)

		g.P("// Get", f.GoName, "Decimal returns the ", f.Desc.Name(), " field as shopspring decimals.")
		g.P("func (x *", m.GoIdent, ") Get", f.GoName, "Decimal() []", dec, " {")
		g.P("src := x.Get", f.GoName, "()")
		g.P("if src == nil {")
		g.P("return nil")
		g.P("}")
		g.P("out := make([]", dec, ", len(src))")
		g.P("for i, p := range src {")
		g.P("out[i] = ", to, "(p)")
		g.P("}")
		g.P("return out")
		g.P("}")
		g.P()
		g.P("// Set", f.GoName, "Decimal replaces the ", f.Desc.Name(), " field. A nil slice clears it.")
		g.P("func (x *", m.GoIdent, ") Set", f.GoName, "Decimal(ds []", dec, ") {")
		g.P("if ds == nil {")
		g.P("x.", f.GoName, " = nil")
		g.P("return")
		g.P("}")
		g.P("out := make([]*", pbElem, ", len(ds))")
		g.P("for i, d := range ds {")
		g.P("out[i] = ", from, "(d)")
		g.P("}")
		g.P("x.", f.GoName, " = out")
		g.P("}")
		g.P()
		return
	}

	g.P("// Get", f.GoName, "Decimal returns the ", f.Desc.Name(), " field as a shopspring decimal.")
	g.P("// It returns the zero decimal when the field is unset.")
	g.P("func (x *", m.GoIdent, ") Get", f.GoName, "Decimal() ", dec, " {")
	g.P("return ", to, "(x.Get", f.GoName, "())")
	g.P("}")
	g.P()
	g.P("// Set", f.GoName, "Decimal sets the ", f.Desc.Name(), " field from a shopspring decimal.")
	g.P("func (x *", m.GoIdent, ") Set", f.GoName, "Decimal(d ", dec, ") {")
	if f.Oneof != nil && !f.Oneof.Desc.IsSynthetic() {
		// Real oneof member: install the wrapper so the case switches.
		g.P("x.", f.Oneof.GoName, " = &", f.GoIdent, "{", f.GoName, ": ", from, "(d)}")
	} else {
		g.P("x.", f.GoName, " = ", from, "(d)")
	}
	g.P("}")
	g.P()
}
